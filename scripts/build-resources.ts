/**
 * Builds the downloadable templates for the marketing resources pages.
 *
 *   npx tsx scripts/build-resources.ts            # build files, previews, manifest
 *   npx tsx scripts/build-resources.ts --verify   # also QuickLook-render every file
 *
 * Writes public/resources/files/*, public/resources/previews/<id>.png and
 * src/lib/resources/files.ts. Previews need macOS QuickLook (qlmanage); on
 * other systems the existing preview PNGs are kept.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { PDFDocument } from "pdf-lib";
import { buildBusinessPlan } from "./resources/content/business-plan";
import { buildDroneQuote } from "./resources/content/drone-quote";
import { buildInvoice } from "./resources/content/invoice";
import { buildPricingSheet } from "./resources/content/pricing-sheet";
import { buildQuestionnaire } from "./resources/content/questionnaire";
import { buildShotList } from "./resources/content/shot-list";
import { buildWorkflow } from "./resources/content/workflow";
import type { ResourceBuild } from "./resources/types";

const ROOT = path.resolve(__dirname, "..");
const FILES_DIR = path.join(ROOT, "public/resources/files");
const PREVIEW_DIR = path.join(ROOT, "public/resources/previews");
const MANIFEST = path.join(ROOT, "src/lib/resources/files.ts");
const PREVIEW_WIDTH = 1200;
const verify = process.argv.includes("--verify");

function pngSize(file: string): { width: number; height: number } {
  const buf = readFileSync(file);
  if (buf.toString("ascii", 1, 4) !== "PNG") throw new Error(`${file} is not a PNG`);
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function hasQuickLook(): boolean {
  try {
    execFileSync("which", ["qlmanage"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

/** Renders the first page with QuickLook. Returns the PNG path or null. */
function quickLook(file: string, size: number): string | null {
  const out = mkdtempSync(path.join(os.tmpdir(), "sp-ql-"));
  try {
    execFileSync("qlmanage", ["-t", "-s", String(size), "-o", out, file], { stdio: "ignore", timeout: 60_000 });
  } catch {
    // qlmanage exits non-zero on some failures; the missing PNG below is the real signal.
  }
  const png = readdirSync(out).find((f) => f.endsWith(".png"));
  return png ? path.join(out, png) : null;
}

async function main() {
  mkdirSync(FILES_DIR, { recursive: true });
  mkdirSync(PREVIEW_DIR, { recursive: true });
  mkdirSync(path.dirname(MANIFEST), { recursive: true });

  const builds: ResourceBuild[] = [];
  for (const build of [buildPricingSheet, buildDroneQuote, buildInvoice, buildShotList, buildBusinessPlan, buildQuestionnaire, buildWorkflow]) {
    builds.push(await build());
  }

  const ql = hasQuickLook();
  const manifest: Record<string, unknown> = {};
  const problems: string[] = [];

  for (const b of builds) {
    for (const f of b.files) {
      const dest = path.join(FILES_DIR, f.filename);
      writeFileSync(dest, f.bytes);
      if (f.format === "pdf") {
        const doc = await PDFDocument.load(f.bytes);
        f.pages = doc.getPageCount();
      }
      console.log(`  ${f.filename.padEnd(64)} ${(f.bytes.length / 1024).toFixed(1).padStart(7)} KB${f.pages ? `  ${f.pages}p` : ""}`);
    }

    const previewPath = path.join(PREVIEW_DIR, `${b.id}.png`);
    if (ql) {
      const pdf = path.join(FILES_DIR, b.previewFrom);
      // QuickLook's size is the longest edge; US Letter is 11/8.5 tall.
      const png = quickLook(pdf, Math.round((PREVIEW_WIDTH * 11) / 8.5));
      if (png) {
        if (existsSync(previewPath)) rmSync(previewPath);
        renameSync(png, previewPath);
      } else problems.push(`preview failed for ${b.id}`);
    }
    if (!existsSync(previewPath)) {
      problems.push(`missing preview ${previewPath}`);
      continue;
    }
    const size = pngSize(previewPath);

    if (verify && ql) {
      for (const f of b.files) {
        const png = quickLook(path.join(FILES_DIR, f.filename), 400);
        console.log(`    QuickLook ${f.format.padEnd(4)} ${png ? "ok " : "FAILED"} ${f.filename}`);
        if (!png) problems.push(`QuickLook could not render ${f.filename}`);
      }
    }

    manifest[b.id] = {
      files: b.files.map((f) => ({
        format: f.format,
        href: `/resources/files/${f.filename}`,
        filename: f.filename,
        bytes: f.bytes.length,
        ...(f.pages ? { pages: f.pages } : {}),
        label: f.label,
      })),
      preview: { src: `/resources/previews/${b.id}.png`, width: size.width, height: size.height },
    };
  }

  const ts =
    "// Generated by scripts/build-resources.ts — do not edit by hand.\n\n" +
    "export type ResourceId =\n" +
    builds.map((b) => `  | "${b.id}"`).join("\n") +
    ";\n\n" +
    'export type ResourceFile = { format: "pdf" | "docx" | "xlsx"; href: string; filename: string; bytes: number; pages?: number; label: string };\n\n' +
    "export const RESOURCE_FILES: Record<ResourceId, { files: ResourceFile[]; preview: { src: string; width: number; height: number } }> = " +
    JSON.stringify(manifest, null, 2) +
    ";\n";
  writeFileSync(MANIFEST, ts);

  if (problems.length) {
    console.error(`\n${problems.length} problem(s):\n - ${problems.join("\n - ")}`);
    process.exitCode = 1;
  } else {
    console.log(`\nBuilt ${builds.length} resources → ${path.relative(ROOT, FILES_DIR)}, manifest → ${path.relative(ROOT, MANIFEST)}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
